package com.vanillara.redalert;

import java.io.File;
import java.io.FileInputStream;
import java.io.FileOutputStream;
import java.io.IOException;
import java.io.InputStream;
import java.io.OutputStream;
import java.util.Locale;

/**
 * File-system side of the game-data importer. Kept free of Android APIs so it
 * can be unit tested on a normal JVM.
 */
public final class GameDataInspector {

    public static final String INSTALL_DIR = "INSTALL";
    public static final String CONFIG_NAME = "REDALERT.INI";
    public static final String MAIN_MIX = "REDALERT.MIX";

    private static final String[] BLOCKED_EXTENSIONS = {
        "ISO", "BIN", "CUE", "ZIP", "7Z", "RAR", "EXE", "MSI", "DMG",
        "MDF", "MDS", "NRG", "IMG", "TMP", "LOG", "DSK", "VHD", "VHDX"
    };

    private GameDataInspector() {
    }

    public static final class Status {
        public final int fileCount;
        public final long byteCount;
        public final boolean hasMix;
        public final boolean hasMainMix;
        public final boolean hasConfig;

        Status(int fileCount, long byteCount, boolean hasMix, boolean hasMainMix, boolean hasConfig) {
            this.fileCount = fileCount;
            this.byteCount = byteCount;
            this.hasMix = hasMix;
            this.hasMainMix = hasMainMix;
            this.hasConfig = hasConfig;
        }

        public boolean isPlayable() {
            return hasMainMix;
        }
    }

    public static Status inspect(File sideDir) {
        int[] counters = new int[] {0, 0, 0}; // files, has mix, has main mix
        long[] bytes = new long[] {0};
        if (sideDir != null && sideDir.isDirectory()) {
            walk(sideDir, counters, bytes);
        }
        boolean hasConfig = sideDir != null
            && (configFile(sideDir).isFile() || new File(sideDir, CONFIG_NAME).isFile());
        return new Status(counters[0], bytes[0], counters[1] != 0, counters[2] != 0, hasConfig);
    }

    private static void walk(File directory, int[] counters, long[] bytes) {
        File[] children = directory.listFiles();
        if (children == null) {
            return;
        }
        for (File child : children) {
            if (child.isDirectory()) {
                walk(child, counters, bytes);
            } else if (child.isFile()) {
                counters[0]++;
                bytes[0] += child.length();
                String name = child.getName().toUpperCase(Locale.US);
                if (name.endsWith(".MIX")) {
                    counters[1] = 1;
                    if (name.equals(MAIN_MIX)) {
                        counters[2] = 1;
                    }
                }
            }
        }
    }

    public static File configFile(File sideDir) {
        return new File(new File(sideDir, INSTALL_DIR), CONFIG_NAME);
    }

    /**
     * The engine always reads assets/redalert/allies/INSTALL/REDALERT.INI.
     * If the imported disc only has REDALERT.INI at its root, mirror it into
     * INSTALL/. If there is no INI at all, write a minimal one so the engine's
     * options/save code has a file to update.
     *
     * @return true when a config file was created or mirrored.
     */
    public static boolean ensureConfig(File sideDir) throws IOException {
        File installDir = new File(sideDir, INSTALL_DIR);
        File config = new File(installDir, CONFIG_NAME);
        if (config.isFile()) {
            return false;
        }
        if (!installDir.isDirectory() && !installDir.mkdirs()) {
            throw new IOException("Unable to create " + installDir.getAbsolutePath());
        }

        File rootConfig = new File(sideDir, CONFIG_NAME);
        if (rootConfig.isFile()) {
            copy(rootConfig, config);
            return true;
        }

        String minimal = "; Generated by Vanillara because no REDALERT.INI was found.\n"
            + "[Options]\n"
            + "GameSpeed=3\n"
            + "ScrollRate=3\n";
        try (OutputStream output = new FileOutputStream(config)) {
            output.write(minimal.getBytes("UTF-8"));
        }
        return true;
    }

    private static void copy(File source, File target) throws IOException {
        File parent = target.getParentFile();
        if (parent != null && !parent.isDirectory() && !parent.mkdirs()) {
            throw new IOException("Unable to create " + parent.getAbsolutePath());
        }
        try (InputStream input = new FileInputStream(source);
             OutputStream output = new FileOutputStream(target)) {
            byte[] buffer = new byte[128 * 1024];
            int read;
            while ((read = input.read(buffer)) != -1) {
                output.write(buffer, 0, read);
            }
        }
    }

    /**
     * Makes an imported path segment safe and matches the upper-case names the
     * 1996 engine uses for its data files.
     */
    public static String normalizeSegment(String name) {
        if (name == null) {
            return "_";
        }
        String normalized = name.trim().toUpperCase(Locale.US)
            .replace('/', '_')
            .replace('\\', '_');
        if (normalized.isEmpty() || ".".equals(normalized) || "..".equals(normalized)) {
            return "_";
        }
        return normalized;
    }

    public static boolean isBlockedFile(String name) {
        if (name == null) {
            return true;
        }
        String upper = name.toUpperCase(Locale.US);
        if (upper.equals(".DS_STORE") || upper.equals("THUMBS.DB") || upper.equals("DESKTOP.INI")) {
            return true;
        }
        int dot = upper.lastIndexOf('.');
        if (dot < 0 || dot == upper.length() - 1) {
            return false;
        }
        String extension = upper.substring(dot + 1);
        for (String blocked : BLOCKED_EXTENSIONS) {
            if (blocked.equals(extension)) {
                return true;
            }
        }
        return false;
    }

    public static void deleteTree(File path) {
        if (path == null || !path.exists()) {
            return;
        }
        File[] children = path.listFiles();
        if (children != null) {
            for (File child : children) {
                deleteTree(child);
            }
        }
        //noinspection ResultOfMethodCallIgnored
        path.delete();
    }
}
